#!/usr/bin/env node
// PreToolUse guard.
// - Write/Edit/NotebookEdit: denies edits to secrets, signing/credential files,
//   package-lock.json and the generated android/ folder.
// - Bash: asks for confirmation when a command looks like it writes to, moves or
//   deletes a secret or credential file (best-effort; reads such as `cat` pass).
const path = require('node:path');
const os = require('node:os');

const projectDir = process.env.CLAUDE_PROJECT_DIR || process.cwd();
const credentialsDir = path.join(os.homedir(), '.credentials');

const ENV_FILE = /^\.env(\..+)?$/;
const ENV_TEMPLATE = /^\.env\.(example|sample|template)$/;
const CREDENTIAL_FILE =
  /(\.(jks|keystore|p8|p12|pem|key|mobileprovision)$)|(-play-.*\.json$)|(^pc-api-.*\.json$)|(^service-account.*\.json$)|(^credentials\.json$)/;

const isEnvFile = (base) => ENV_FILE.test(base) && !ENV_TEMPLATE.test(base);

function reasonForPath(filePath) {
  const abs = path.resolve(projectDir, filePath);
  const rel = path.relative(projectDir, abs).split(path.sep).join('/');
  const base = path.basename(abs);
  const insideProject = !rel.startsWith('..') && !path.isAbsolute(rel);

  if (abs === credentialsDir || abs.startsWith(credentialsDir + path.sep) || CREDENTIAL_FILE.test(base)) {
    return `${base} is a signing or service-account credential. Do not edit it; ask the user to change it themselves.`;
  }
  if (isEnvFile(base)) {
    return `${base} holds local secrets (Neon settings). Ask the user to edit it themselves; build-time secrets live in EAS env (eas env:set).`;
  }
  if (insideProject && rel === 'package-lock.json') {
    return 'package-lock.json is generated. Change dependencies with npm install / npm uninstall (or npx expo install) instead of editing the lockfile.';
  }
  if (insideProject && (rel === 'android' || rel.startsWith('android/'))) {
    return 'android/ is generated by expo prebuild and gitignored, so edits there are lost. Change app.config.js or a config plugin instead.';
  }
  return null;
}

// Bash: a segment that names a protected file and writes to it.
const PROTECTED_TOKEN = /(^|[\s'"=/<>])(\.env(\.[\w.-]+)?|[\w.-]*-play-[\w.-]*\.json|service-account[\w.-]*\.json|[\w.-]+\.(jks|keystore|p8|p12|pem|key)|\.credentials\/)(?=$|[\s'";|&)])/g;
const WRITE_VERB = /^\s*(sudo\s+)?(rm|mv|cp|tee|truncate|shred|dd|chmod|ln)\b/;
const IN_PLACE = /\b(sed|perl)\s+[^|;&]*-[a-zA-Z]*i\b/;
const REDIRECT_TO_PROTECTED = /(^|[^0-9&])>>?\s*['"]?[^\s'";|&]*(\.env(\.[\w.-]+)?|-play-[\w.-]*\.json|service-account[\w.-]*\.json|\.credentials\/)/;

function reasonForCommand(command) {
  const segments = command.split(/\|\||&&|[;|\n]/);
  for (const segment of segments) {
    const target = [...segment.matchAll(PROTECTED_TOKEN)].map((m) => m[2]).find((t) => !ENV_TEMPLATE.test(t));
    if (!target) continue;
    if (WRITE_VERB.test(segment) || IN_PLACE.test(segment) || /\btee\b/.test(segment) || REDIRECT_TO_PROTECTED.test(segment)) {
      return `This command appears to modify ${target}, a secret or credential file. Confirm only if you meant it.`;
    }
  }
  return null;
}

function respond(decision, reason) {
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'PreToolUse',
        permissionDecision: decision,
        permissionDecisionReason: reason,
      },
    }),
  );
}

let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => (raw += chunk));
process.stdin.on('end', () => {
  let input;
  try {
    input = JSON.parse(raw);
  } catch {
    return;
  }
  const tool = input.tool_name;
  const toolInput = input.tool_input || {};

  if (tool === 'Bash') {
    const reason = typeof toolInput.command === 'string' ? reasonForCommand(toolInput.command) : null;
    if (reason) respond('ask', reason);
    return;
  }

  const target = toolInput.file_path || toolInput.notebook_path;
  if (typeof target !== 'string') return;
  const reason = reasonForPath(target);
  if (reason) respond('deny', reason);
});
